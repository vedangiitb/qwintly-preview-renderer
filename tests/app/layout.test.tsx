import React from 'react';
import { render, screen } from '@testing-library/react';
import { describe, it, expect, vi } from 'vitest';
import RootLayout, { metadata } from '../../app/layout';

vi.mock('next/font/google', () => ({
  Geist: () => ({ variable: 'mocked-geist-sans' }),
  Geist_Mono: () => ({ variable: 'mocked-geist-mono' }),
}));

describe('RootLayout Component', () => {
  it('should render HTML and Body tags with correct classes and metadata', () => {
    render(
      <RootLayout>
        <div data-testid="child-element">Test Child</div>
      </RootLayout>
    );

    const child = screen.getByTestId('child-element');
    expect(child).toBeInTheDocument();

    const htmlElement = document.documentElement;
    expect(htmlElement).toHaveClass('mocked-geist-sans');
    expect(htmlElement).toHaveClass('mocked-geist-mono');
    expect(htmlElement).toHaveClass('h-full');
    expect(htmlElement).toHaveClass('antialiased');

    expect(metadata.title).toBe('Create Next App');
    expect(metadata.description).toBe('Generated by create next app');
  });
});
